const DICTS: Partial<Record<Lang, Dict>> = {
  EN,
  ES,
  FR,
  DE,
  PT,
  IT,
  NL,
  RU,
  TR,
  AR,
  HI,
  UR,
  ZH,
  JA,
  KO,
  ID,
};

const STORAGE_KEY = "wv_lang";

const CODES = new Set<string>(LANGUAGES.map((entry) => entry.code));

function isLang(value: unknown): value is Lang {
  return typeof value === "string" && CODES.has(value);
}

function readLang(): Lang {
  try {
    const raw = window.localStorage.getItem(STORAGE_KEY);
    return isLang(raw) ? raw : "EN";
  } catch {
    return "EN";
  }
}

function persistLang(lang: Lang): void {
  try {
    window.localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    /* storage unavailable */
  }
}

const langStore = createExternalStore<Lang>(readLang, "EN");

function interpolate(
  template: string,
  vars?: Record<string, string | number>,
): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in vars ? String(vars[key]) : match,
  );
}

export type Translate = (
  key: TranslationKey,
  vars?: Record<string, string | number>,
) => string;

export function translate(
  lang: Lang,
  key: TranslationKey,
  vars?: Record<string, string | number>,
): string {
  const template = DICTS[lang]?.[key] ?? EN[key] ?? key;
  return interpolate(template, vars);
}

interface I18nValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: Translate;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const lang = useSyncExternalStore(
    langStore.subscribe,
    langStore.getSnapshot,
    langStore.getServerSnapshot,
  );

  useEffect(() => {
    const entry = LANGUAGES.find((item) => item.code === lang);
    if (typeof document !== "undefined") {
      document.documentElement.lang = lang.toLowerCase();
      document.documentElement.dir = entry?.dir ?? "ltr";
    }
  }, [lang]);

  const setLang = useCallback((next: Lang) => {
    langStore.set(next);
    persistLang(next);
  }, []);

  const t = useCallback<Translate>(
    (key, vars) => translate(lang, key, vars),
    [lang],
  );

  const value = useMemo<I18nValue>(() => ({ lang, setLang, t }), [lang, setLang, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used within I18nProvider");
  }
  return context;
}
